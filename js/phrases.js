/*
 * Ablak — domain phrase corpus
 * ---------------------------------------------------------------------------
 * Each entry is one thing a Hungarian official, bank clerk or receptionist
 * actually says across a counter. This is NOT a general translation
 * dictionary: it is a narrow, curated, high-confidence corpus for three
 * specific rooms where getting it wrong has real consequences.
 *
 * Why a corpus instead of general machine translation:
 *   1. Bureaucratic Hungarian is agglutinative and formulaic. "Kérem a
 *      lakcímkártyáját" is a fixed move in a fixed script, not free prose.
 *   2. A general translator renders words. A newcomer at a counter does not
 *      need words — they need to know WHICH DOCUMENT to pull out of the folder
 *      and WHAT TO SAY BACK. That is an action, not a translation.
 *   3. It is auditable. Every output in this file was written once and can be
 *      checked by a human. An LLM's output cannot be, and a hallucinated
 *      instruction at an immigration counter can cost a residence permit.
 *
 * Field reference:
 *   id          stable key, used by tests
 *   scenario    immigration | bank | clinic | supermarket | generic
 *   hu          the canonical form of the phrase
 *   variants    other real phrasings of the same move (widens recall)
 *   keywords    content words that identify this move; drive the stem match
 *   ru_meaning  what they are asking, in plain Russian
 *   ru_action   what the user should physically do right now
 *   reply_hu    a safe Hungarian reply, spoken aloud for the user to repeat
 *   reply_ru    gloss of reply_hu, so the user knows what they are saying
 *   ru_doc      document to produce, or null (en_doc is its English form)
 *   risk        low | medium | high — high means never auto-answer, see app.js
 */

